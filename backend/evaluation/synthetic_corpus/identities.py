"""Fictional identities for the firm and every case participant.

Names are generated by code (Faker ``de_AT``), never by the language model, so
the corpus never carries real names from seed decisions. Generation is seeded
and therefore reproducible; names are unique within a run and checked against a
blocklist (for example lawyer and judge names found in RIS seed decisions).
"""

from __future__ import annotations

import hashlib
import random
import re
import unicodedata
from typing import Iterable, Optional

from faker import Faker

from .models import Firm, Identity, PersonKind

_LEGAL_FORMS = ["GmbH", "GmbH", "GmbH", "KG", "OG", "e.U.", "GmbH & Co KG", "AG"]
_INDUSTRY_HINTS = {
    "default": ["Handel", "Service", "Technik", "Logistik", "Consulting", "Bau", "Immobilien", "Holz", "Elektro"],
    "bau": ["Bau", "Baumeister", "Fassaden", "Installationen", "Dach", "Fenster"],
    "immobilien": ["Immobilien", "Hausverwaltung", "Realitäten"],
    "it": ["IT", "Software", "Digital", "Data"],
}
_TITLES_NATURAL = ["", "", "", "", "Mag.", "Ing.", "Dr.", "DI", "MMag.", "BSc"]
_TITLES_LAWYER = ["Dr.", "Mag.", "Mag. Dr.", "MMag."]
_TITLES_JUDGE = ["Mag.", "Dr.", "Mag. Dr."]

# Real postcode/town pairs (Faker de_AT mixes them freely). Vienna is handled separately.
_PLACES: dict[str, str] = {
    "2340": "Mödling", "2500": "Baden", "3100": "St. Pölten", "3400": "Klosterneuburg", "2700": "Wiener Neustadt",
    "2100": "Korneuburg", "2232": "Deutsch-Wagram", "3500": "Krems an der Donau", "3300": "Amstetten",
    "2620": "Neunkirchen", "2380": "Perchtoldsdorf", "2361": "Laxenburg", "4020": "Linz", "4600": "Wels",
    "8010": "Graz", "8700": "Leoben", "5020": "Salzburg", "6020": "Innsbruck", "9020": "Klagenfurt am Wörthersee",
    "7000": "Eisenstadt", "6900": "Bregenz",
}


def _slug(text: str) -> str:
    text = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode("ascii")
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def _house_number(street: str, rng: random.Random) -> str:
    """Replace Faker's house numbers (0 to 999) with realistic ones, sometimes with a door number."""
    number = str(rng.randint(1, 85))
    if rng.random() < 0.35:
        number += f"/{rng.randint(1, 24)}"
    return re.sub(r"\s+[\d/]+[a-z]?$", f" {number}", street.strip())


def _seed_int(*parts: object) -> int:
    return int(hashlib.sha256("|".join(map(str, parts)).encode()).hexdigest()[:12], 16)


class IdentityFactory:
    """Creates unique fictional people and organisations.

    Args:
        seed: Base random seed (from ``corpus.random_seed``).
        locale: Faker locale, ``de_AT`` by default.
        blocklist: Names that must never be produced (case-insensitive substring match on surname).
    """

    def __init__(self, seed: int, locale: str = "de_AT", blocklist: Iterable[str] = ()):  # noqa: D107
        self.seed = seed
        self.locale = locale
        self.used_names: set[str] = set()
        self.used_surnames: set[str] = set()
        self.blocked_surnames = {b.strip().lower() for b in blocklist if b and len(b.strip()) >= 3}

    def _faker(self, *scope: object) -> tuple[Faker, random.Random]:
        fk = Faker(self.locale)
        n = _seed_int(self.seed, *scope)
        fk.seed_instance(n)
        return fk, random.Random(n)

    def _unique_person_name(self, fk: Faker, rng: random.Random, gender: Optional[str] = None) -> tuple[str, str]:
        for _ in range(200):
            if gender == "female":
                first = fk.first_name_female()
            elif gender == "male":
                first = fk.first_name_male()
            else:
                first = fk.first_name()
            last = fk.last_name()
            full = f"{first} {last}"
            if full.lower() in self.used_names or last.lower() in self.used_surnames or last.lower() in self.blocked_surnames:
                continue
            self.used_names.add(full.lower())
            self.used_surnames.add(last.lower())
            return first, last
        raise RuntimeError("could not generate a unique name")

    def person(
        self,
        pid: str,
        role: str,
        label: str,
        *,
        scope: str,
        kind: PersonKind = "natural",
        title_pool: Optional[list[str]] = None,
        vienna: bool = False,
        email_domain: Optional[str] = None,
        industry: str = "default",
        description: str = "",
        gender: Optional[str] = None,
        name_word: Optional[str] = None,
        legal_form: Optional[str] = None,
        postcode: Optional[str] = None,
    ) -> Identity:
        """Create one identity.

        Args:
            pid: Stable id inside the case (e.g. ``P1``).
            role: Machine role (``mandant``, ``gegner``, ``richter`` ...).
            label: German role label for documents.
            scope: Seed scope, usually the case id, so cases are independent.
            kind: ``natural`` person or ``legal`` entity.
            title_pool: Academic titles to choose from.
            vienna: Use a Vienna address.
            email_domain: Fixed email domain (e.g. the firm's).
            industry: Hint for company names.
            description: Free text kept on the identity.
            gender: ``female``/``male`` for natural persons (first-name choice).
            name_word: Word used in a company name (e.g. ``Tischlerei``).
            legal_form: Fixed legal form for companies (e.g. ``GmbH``).
            postcode: Fixed postcode (e.g. ``1020`` for Wien-Leopoldstadt).
        """
        fk, rng = self._faker(scope, pid, role)
        street = _house_number(fk.street_address(), rng)
        if postcode and postcode.startswith("1") and len(postcode) == 4:
            city = "Wien"
        elif postcode:
            city = _PLACES.get(postcode, fk.city())
        elif vienna:
            district = rng.randint(1, 23)
            postcode, city = f"1{district:02d}0", "Wien"
        else:
            postcode = rng.choice(sorted(_PLACES))
            city = _PLACES[postcode]
        phone = f"+43 {rng.choice(['1', '664', '676', '699', '650', '316', '732'])} {rng.randint(100000, 9999999)}"
        if kind == "legal":
            for _ in range(200):
                surname = fk.last_name()
                words = [name_word] if name_word else _INDUSTRY_HINTS.get(industry, _INDUSTRY_HINTS["default"])
                form = legal_form or rng.choice(_LEGAL_FORMS)
                name = f"{surname} {rng.choice(words)} {form}"
                if (name.lower() not in self.used_names and surname.lower() not in self.blocked_surnames
                        and surname.lower() not in self.used_surnames):
                    self.used_names.add(name.lower())
                    self.used_surnames.add(surname.lower())
                    break
            domain = email_domain or f"{_slug(name.split(' ')[0] + '-' + name.split(' ')[1])}.at"
            return Identity(
                id=pid,
                role=role,
                kind="legal",
                label=label,
                name=name,
                street=street,
                postcode=postcode,
                city=city,
                email=f"office@{domain}",
                phone=phone,
                iban=fk.iban(),
                company_register_no=f"FN {rng.randint(100000, 699999)}{rng.choice('abcdfghikmpstvwxyz')}",
                description=description,
            )
        first, last = self._unique_person_name(fk, rng, gender)
        title = rng.choice(title_pool if title_pool is not None else _TITLES_NATURAL)
        domain = email_domain or rng.choice(["gmx.at", "aon.at", "chello.at", "gmail.com", "a1.net"])
        birth = fk.date_of_birth(minimum_age=24, maximum_age=78).isoformat()
        return Identity(
            id=pid,
            role=role,
            kind="natural",
            label=label,
            name=f"{first} {last}",
            title=title,
            street=street,
            postcode=postcode,
            city=city,
            email=f"{_slug(first)}.{_slug(last)}@{domain}",
            phone=phone,
            iban=fk.iban(),
            birth_date=birth,
            description=description,
        )

    def firm(self, name: Optional[str], city: str, postcode: Optional[str], street: Optional[str],
             email_domain: Optional[str], partners: int, associates: int, assistants: int) -> Firm:
        """Create the fictional firm and its staff."""
        fk, rng = self._faker("firm")
        partner_ids = [f"K{i + 1}" for i in range(partners)]
        staff: list[Identity] = []
        surnames: list[str] = []
        for i, pid in enumerate(partner_ids):
            g = "male" if i % 2 == 0 else "female"
            p = self.person(pid, "kanzlei_partner", "Rechtsanwalt" if g == "male" else "Rechtsanwältin", scope="firm",
                            title_pool=_TITLES_LAWYER, vienna=True, gender=g)
            surnames.append(p.name.split(" ")[-1])
            staff.append(p)
        firm_name = name or (
            f"{surnames[0]} & {surnames[1]} Rechtsanwälte OG" if len(surnames) > 1 else f"Rechtsanwaltskanzlei {surnames[0]}"
        )
        domain = email_domain or f"{_slug('-'.join(surnames[:2]))}-law.at"
        for s in staff:
            first, last = s.name.split(" ", 1)
            s.email = f"{_slug(first)[0]}.{_slug(last)}@{domain}"
        for i in range(associates):
            g = "female" if i % 2 == 0 else "male"
            a = self.person(f"K{partners + i + 1}", "kanzlei_associate",
                            "Rechtsanwaltsanwärterin" if g == "female" else "Rechtsanwaltsanwärter", scope="firm",
                            title_pool=["Mag.", "Mag.", "Dr.", "MMag."], vienna=True, email_domain=domain, gender=g)
            staff.append(a)
        for i in range(assistants):
            g = "female" if i % 2 == 0 else "male"
            a = self.person(f"K{partners + associates + i + 1}", "kanzlei_assistenz",
                            "Kanzleiassistentin" if g == "female" else "Kanzleiassistent", scope="firm",
                            title_pool=[""], vienna=True, email_domain=domain, gender=g)
            staff.append(a)
        district = rng.randint(1, 9)
        office_street = street or _house_number(fk.street_address(), rng)
        office_postcode = postcode or f"1{district:02d}0"
        office_phone = f"+43 1 {rng.randint(2000000, 9999999)}"
        for i, s in enumerate(staff):
            # lawyers and staff are reached at the office, not at home
            s.street, s.postcode, s.city = office_street, office_postcode, city
            s.phone = f"{office_phone}-{11 + i}"
        return Firm(
            name=firm_name,
            street=office_street,
            postcode=office_postcode,
            city=city,
            phone=office_phone,
            email_domain=domain,
            uid=f"ATU{rng.randint(10000000, 99999999)}",
            staff=staff,
        )


_NAME_PATTERNS = [
    # "Dr. Max Mustermann", "Mag. Anna Maria Huber", "MMag. Dr. Paul Berger"
    re.compile(r"\b(?:(?:Mag|Dr|MMag|DI|Ing|Hon\.-Prof|Univ\.-Prof|Prof)\.\s*)+(?:[A-ZÄÖÜ][a-zäöüß]+\s){0,2}([A-ZÄÖÜ][a-zäöüß]{2,}(?:-[A-ZÄÖÜ][a-zäöüß]+)?)"),
    # "Rechtsanwalt Max Mustermann", "Richterin Anna Huber"
    re.compile(r"\b(?:Rechtsanwalt|Rechtsanwältin|Richter|Richterin|Hofrat|Hofrätin|Senatspräsident(?:in)?)\s+(?:[A-ZÄÖÜ][a-zäöüß]+\s){0,2}([A-ZÄÖÜ][a-zäöüß]{2,})"),
]


def extract_blocked_surnames(texts: Iterable[str]) -> set[str]:
    """Collect surnames of lawyers and judges named in seed texts.

    RIS decisions mask parties but name lawyers and judges in full; those names
    must not reappear in generated documents.
    """
    found: set[str] = set()
    for text in texts:
        for pattern in _NAME_PATTERNS:
            for m in pattern.finditer(text):
                found.add(m.group(1))
    return {s for s in found if s.lower() not in {"wien", "graz", "linz", "salzburg", "innsbruck", "partner", "gmbh"}}
